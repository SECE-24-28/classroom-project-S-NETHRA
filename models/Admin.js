const mongoose = require("mongoose");
const admin = new mongoose.Schema({
  firstName: {
    type: String,
    required: true,
    trim: true
  },
  secondName: {
    type: String,
    trim: true
  },
  email: {
    type: String,
    required: true,
    unique: true,
    lowercase: true,
    trim: true
  },
  mobileNumber: {
    type: String,
    required: true,
    unique: true
  },
  password: {
    type: String,
    required: true,
    minlength: 6
  },
  role: {
    type: String,
    default: 'admin'
  }
}, {
  timestamps: true
});
module.exports = mongoose.model("Admin", admin);
